"""Writes zoom.h for vdmod.c: the new gallery zoom function (../gallery_zoom.py) and the original bytes
it replaces, with a mask that skips the bytes Windows relocates (the exe may load at another base).
  python -I gen_zoom.py path/to/original/VD_BHIKKHUNI.exe
"""
import os, sys, pefile
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..'))
import gallery_zoom as G

pe = pefile.PE(sys.argv[1])
img = pe.get_memory_mapped_image()
rva = G.VA - pe.OPTIONAL_HEADER.ImageBase
old, mask = img[rva:rva + G.SIZE], [1] * G.SIZE
for blk in pe.DIRECTORY_ENTRY_BASERELOC:
    for r in blk.entries:
        if r.type:
            for i in range(r.rva - rva, r.rva - rva + 4):
                if 0 <= i < G.SIZE: mask[i] = 0
new, _ = G.assemble()
arr = lambda name, b: f'static const unsigned char {name}[{len(b)}] = {{' + ','.join(map(str, b)) + '};\n'
open(os.path.join(here, 'zoom.h'), 'w').write(
    f'/* generated by gen_zoom.py from gallery_zoom.py - do not edit */\n#define ZOOM_VA {G.VA:#x}\n#define ZOOM_SIZE {G.SIZE}\n'
    + arr('zoom_old', old) + arr('zoom_mask', mask) + arr('zoom_new', new))
print('zoom.h:', G.SIZE, 'bytes,', mask.count(0), 'relocated bytes masked')
